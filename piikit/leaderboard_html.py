def _bar(f1: float) -> str:
    pct = int(f1 * 100)
    return (f'<span class="bar-wrap"><span class="bar" style="width:{pct}px"></span></span>')


def _f1_class(f1: float) -> str:
    return "zero" if f1 == 0 else "f1"


def _medal(rank: int) -> str:
    return {1: "medal-1", 2: "medal-2", 3: "medal-3"}.get(rank, "")


def render_html(results: list, frozen_id: str) -> str:
    sections_html = ""

    text = [r for r in results if r["task"] == "text" and r["frozen_id"] == frozen_id]
    if text:
        text.sort(key=lambda r: (-r["metrics"]["strict"]["f1"], r["name"]))
        rows = []
        for i, r in enumerate(text, 1):
            s = r["metrics"]["strict"]
            lo, hi = s["f1_ci95"]
            fa = r.get("false_alarm_rate_on_clean_records")
            fa_str = "n/a" if fa is None else f"{fa:.1%}"
            medal = _medal(i)
            rows.append(
                f'<tr>'
                f'<td class="rank {medal}">{i}</td>'
                f'<td><strong>{r["name"]}</strong></td>'
                f'<td><span class="tag">{r["label_set"]}</span></td>'
                f'<td class="{_f1_class(s["f1"])}">{s["f1"]:.3f}{_bar(s["f1"])}</td>'
                f'<td class="ci">{lo:.3f}–{hi:.3f}</td>'
                f'<td>{s["precision"]:.3f}</td>'
                f'<td>{s["recall"]:.3f}</td>'
                f'<td>{fa_str}</td>'
                f'</tr>'
            )
        sections_html += _TEXT_SECTION.format(rows="\n      ".join(rows))

    docs = [r for r in results if r["task"] == "docs" and r["frozen_id"] == frozen_id]
    if docs:
        docs.sort(key=lambda r: (-r["metrics"]["iou_0.5"]["f1"], r["name"]))
        rows = []
        for i, r in enumerate(docs, 1):
            m = r["metrics"]["iou_0.5"]
            lo, hi = m["f1_ci95"]
            medal = _medal(i)
            rows.append(
                f'<tr>'
                f'<td class="rank {medal}">{i}</td>'
                f'<td><strong>{r["name"]}</strong></td>'
                f'<td><span class="tag">{r["label_set"]}</span></td>'
                f'<td class="{_f1_class(m["f1"])}">{m["f1"]:.3f}{_bar(m["f1"])}</td>'
                f'<td class="ci">{lo:.3f}–{hi:.3f}</td>'
                f'<td>{m["precision"]:.3f}</td>'
                f'<td>{m["recall"]:.3f}</td>'
                f'</tr>'
            )
        sections_html += _DOCS_SECTION.format(rows="\n      ".join(rows))

    if not sections_html:
        sections_html = '<p style="color:#64748b;text-align:center;">No results yet.</p>'

    return _HTML_TEMPLATE.format(frozen_id=frozen_id[:16], sections=sections_html)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bench", type=Path, default=Path("benchmark"))
    parser.add_argument("--out", type=Path, default=Path("docs/leaderboard.html"))
    args = parser.parse_args()

    frozen = json.loads((args.bench / "FROZEN.json").read_text(encoding="utf-8"))
    results = []
    for p in sorted((args.bench / "results").glob("*.json")):
        results.append(json.loads(p.read_text(encoding="utf-8")))

    html = render_html(results, frozen["frozen_id"])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(html, encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
