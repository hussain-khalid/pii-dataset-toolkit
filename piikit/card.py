"""Render the dataset card (DATASET_CARD.md) from the real numbers of a release."""

from piikit.schema import LABELS
from piikit.splits import SPLITS


def _table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(" --- " for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def render_card(stats: dict) -> str:
    t, d = stats["text"], stats["docs"]
    p = stats["parameters"]

    split_rows = [
        (s, t["per_split"][s]["records"], d["per_split"][s]["records"]) for s in SPLITS
    ]
    split_rows.append(("**total**", t["kept"], d["kept"]))

    text_label_rows = [
        (label, *[t["per_split"][s]["labels"].get(label, 0) for s in SPLITS],
         sum(t["per_split"][s]["labels"].get(label, 0) for s in SPLITS))
        for label in LABELS
    ]
    doc_label_rows = [
        (label, *[d["per_split"][s]["labels"].get(label, 0) for s in SPLITS],
         sum(d["per_split"][s]["labels"].get(label, 0) for s in SPLITS))
        for label in LABELS
    ]
    doc_types = sorted({k for s in SPLITS for k in d["per_split"][s]["doc_types"]})
    doc_type_rows = [
        (k, *[d["per_split"][s]["doc_types"].get(k, 0) for s in SPLITS],
         sum(d["per_split"][s]["doc_types"].get(k, 0) for s in SPLITS))
        for k in doc_types
    ]

    return f"""# Dataset card: PII Dataset Toolkit release {p["version"]}

## Summary

A small **fully synthetic** dataset for personal-data (PII) detection, in two modalities:

- **text**: short messages with character-offset span labels.
- **document images**: invoices, forms and ID-style cards with pixel bounding boxes around each PII field.

No real person's data is included. Every name, address, email, phone number, ID number and
date of birth was generated by the code in this repository.

## Contents

{_table(["split", "text records", "document images"], split_rows)}

Labels: {", ".join(f"`{l}`" for l in LABELS)}.

### Text: labelled spans per split

{_table(["label", *SPLITS, "total"], text_label_rows)}

### Documents: labelled fields per split

{_table(["label", *SPLITS, "total"], doc_label_rows)}

### Documents: type per split

{_table(["doc_type", *SPLITS, "total"], doc_type_rows)}

## Format

- `text/{{train,validation,test}}.jsonl`: one record per line with `id`, `text`, `spans`
  (`start`, `end`, `label`, `text`; offsets index into `text`, end exclusive), plus
  `modality` and `provenance`.
- `docs/{{train,validation,test}}.jsonl`: one record per line with `id`, `image`, `width`,
  `height`, `doc_type`, `fields` (`label`, `text`, `bbox` as `[x0, y0, x1, y1]`), plus
  `modality` and `provenance`. Images are in `docs/images/`.
- `MANIFEST.json` lists every file with its SHA-256 checksum and record count.

## How it was built

1. Generate text and document data with fixed seeds (input files: `{stats["inputs"]["text"]["name"]}`,
   `{stats["inputs"]["docs"]["name"]}`).
2. Remove duplicates (see below).
3. Assign each remaining record to a split from a hash of its id and seed {p["seed"]}
   ({p["ratios"][0]}% train, {p["ratios"][1]}% validation, {p["ratios"][2]}% test).
4. Attach a provenance block to every record and write checksums to `MANIFEST.json`.

## Deduplication

| modality | input records | exact duplicates | near-duplicates | identical images | kept |
| --- | --- | --- | --- | --- | --- |
| text | {t["input"]} | {t["removed"].get("exact_duplicate", 0)} | {t["removed"].get("near_duplicate", 0)} | n/a | {t["kept"]} |
| documents | {d["input"]} | {d["removed"].get("exact_duplicate", 0)} | n/a | {d["removed"].get("identical_image", 0)} | {d["kept"]} |

Text near-duplicates are records whose word 3-gram shingles have Jaccard similarity of at
least {p["near_dup_threshold"]}. Every removed record is listed with its reason in `dedup_report.json`.

## Provenance and licence

Every record carries a `provenance` block: the generator that made it, the input file and
line it came from, the input file's SHA-256, a `synthetic: true` flag and the licence.
All content is synthetic and released as **{stats["license"]}**. Code licence is separate.

## Intended use

Developing and testing PII-detection pipelines, evaluation harnesses and data tooling.
It is not suitable for training or evaluating a production PII detector on its own.

## Limitations

- Text comes from a small set of templates, so sentence structure is far less varied than real messages.
- Names, streets and cities are drawn from short word lists. The same pools feed every split, so
  validation and test scores overstate how well a model handles unseen names. A generated
  name can also coincide with a real person by chance.
- Documents use one default font, clean backgrounds and axis-aligned boxes. There is no scan
  noise, rotation, handwriting or photographed text.
- Labels are exact by construction, which real annotated data never is.
- Split sizes are small, so metrics on the validation and test splits are noisy.

## Reproduce

```bash
python -m piikit.text_gen --n 1000 --seed 42 --out data/raw/text.jsonl
python -m piikit.doc_gen --n 200 --seed 42 --out-dir data/raw/docs
python -m piikit.build_release --text data/raw/text.jsonl --docs data/raw/docs/docs.jsonl \\
    --out-dir data/release/v{p["version"]} --seed {p["seed"]} --version {p["version"]}
python -m piikit.validate_release data/release/v{p["version"]}
```
"""